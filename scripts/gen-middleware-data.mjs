#!/usr/bin/env node
/**
 * Generates `middleware-data.js` — the two things Edge Middleware needs but
 * cannot read at runtime (there is no filesystem on the edge):
 *
 *   KNOWN_PATHS  every page-like path the site actually answers, so middleware
 *                can tell "this path exists" from "this is a 404" without a
 *                round-trip. Built from the .html/.md files on disk PLUS every
 *                `rewrites`/`redirects` source in vercel.json — middleware runs
 *                BEFORE those rules, so a redirect source that is missing here
 *                would be answered as a 404 instead of being redirected.
 *
 *   NOT_FOUND_MD the body of 404.md, so the 404 response can carry a real
 *                markdown body for agents (is-agentic `agent-friendly-404`).
 *
 * Run: npm run gen-middleware-data   (also runs as part of `npm run check-all`)
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const SKIP_DIRS = new Set(['node_modules', '.git', '.claude', '.github', 'docs', 'scripts', 'lib']);

/** every .html / .md file, as a site path */
function walk(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    const abs = join(dir, entry);
    if (statSync(abs).isDirectory()) {
      if (!SKIP_DIRS.has(entry)) walk(abs, out);
    } else if (/\.(html|md)$/i.test(entry)) {
      out.push('/' + relative(root, abs).split(sep).join('/'));
    }
  }
  return out;
}

const paths = new Set(['/']);
for (const p of walk(root)) {
  paths.add(p);
  if (p.endsWith('/index.html')) paths.add(p.slice(0, -'index.html'.length) || '/');
  if (p.endsWith('.html')) paths.add(p.slice(0, -'.html'.length)); // extensionless twin
}

// vercel.json rewrite/redirect sources — middleware runs before both
const vercel = JSON.parse(readFileSync(join(root, 'vercel.json'), 'utf8'));
for (const rule of [...(vercel.rewrites || []), ...(vercel.redirects || [])]) {
  paths.add(rule.source);
  try { paths.add(decodeURIComponent(rule.source)); } catch { /* leave as-is */ }
}

// trailing-slash twins — Vercel answers both forms
for (const p of [...paths]) if (p !== '/' && !p.endsWith('/')) paths.add(p + '/');

// Guard: every URL we advertise in sitemap.xml MUST be known, otherwise the
// middleware would answer a real page with a 404 for agents and crawlers.
const sitemap = readFileSync(join(root, 'sitemap.xml'), 'utf8');
const missing = [...sitemap.matchAll(/<loc>\s*([^<]+?)\s*<\/loc>/g)]
  .map((m) => new URL(m[1]).pathname)
  .filter((p) => !paths.has(p));
if (missing.length) {
  console.error('FAIL: sitemap URLs missing from KNOWN_PATHS: ' + missing.join(', '));
  process.exit(1);
}

const md = readFileSync(join(root, '404.md'), 'utf8');
const sorted = [...paths].sort();

const out = `// GENERATED by scripts/gen-middleware-data.mjs — do not edit by hand.
// Regenerate with: npm run gen-middleware-data

export const KNOWN_PATHS = new Set(${JSON.stringify(sorted, null, 2)});

export const NOT_FOUND_MD = ${JSON.stringify(md)};
`;

writeFileSync(join(root, 'middleware-data.js'), out);
console.log(`middleware-data.js: ${sorted.length} known paths, 404.md ${md.length} bytes`);
